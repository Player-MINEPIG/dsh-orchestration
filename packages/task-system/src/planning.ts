import { ExecutionModelChoice } from "./execution-models.js";
import type {
  DecisionRequest,
  DecisionReceipt,
} from "./decision-types.js";
import type {
  TaskDecisionSnapshot,
  TaskDecisionProposal,
  TaskPolicyResult,
} from "./task-policy.js";
import { createHash } from "node:crypto";
import { TaskLedger, TaskError, canonical } from "./ledger.js";
import type { ExecutionRoute, Json } from "./contracts.js";
// Same canonical JSON digest as the decision contract, without loading its optional runtime.
const digest = (value: unknown): string =>
  createHash("sha256").update(canonical(value)).digest("hex");
import { askTaskDecision, type DecisionServicePort } from "./decision-call.js";
export type { DecisionServicePort } from "./decision-call.js";
export interface PlanningInput {
  requestId: string;
  title: string;
  description: string;
  /** Optional decision-call overrides. Workload routing is selected from the catalog unless route is explicit. */
  provider?: string;
  model?: string;
  reasoningEffort?: string;
  observationCandidateId?: string;
  /** Explicit caller-owned execution assignment; never generated by the decision model. */
  route?: ExecutionRoute;
  /** Explicit executor constraint; workload policy still belongs to that node. */
  nodeId?: string;
  executionModel?: ExecutionModelChoice;
  /** Explicit Task workspace constraint; not a scheduler-model answer. */
  workspaceId?: string;
  /** Host-bound project scope, never taken from tool arguments. */
  projectId?: string;
  /** Host-bound existing task; persistence cannot create a duplicate. */
  taskId?: string;
  expectedActionVersion?: string;
  /** Operator feedback for this retry; persisted with the decision, not the original Task intent. */
  retryPrompt?: string;
  /** Host-owned previous Run; keeps its pinned template/window and parent binding. */
  retrySourceRunId?: string;
  automaticResultRetry?: boolean;
}
/** A consumer of the independent decision plugin. All grants are operator-owned policy. */
export class TaskPlanner {
  constructor(
    private ledger: TaskLedger,
    private decisions:
      | DecisionServicePort
      | (() => DecisionServicePort | undefined)
      | undefined,
    private catalog: () => TaskDecisionSnapshot,
    private authorize: (proposal: TaskDecisionProposal) => void,
    private now: () => number = Date.now,
    private enabled: () => boolean = () => true,
    private decisionProvider: () => string | undefined = () => undefined,
  ) {}
  async planObservation(
    candidateId: string,
    options: {
      signal?: AbortSignal;
      provider?: string;
      model?: string;
      reasoningEffort?: string;
    } = {},
  ) {
    const candidate = this.ledger
      .observationCandidates()
      .find((c) => c.candidateId === candidateId);
    if (!candidate || candidate.state !== "pending")
      throw new TaskError("CONFLICT", "Observation is not pending");
    return this.plan(
      {
        requestId: `observe:${candidateId}`,
        title: candidate.title,
        description: candidate.body,
        observationCandidateId: candidateId,
        provider: options.provider,
        model: options.model,
        reasoningEffort: options.reasoningEffort,
      },
      { signal: options.signal },
    );
  }
  private snapshot(input: PlanningInput) {
    const base = this.catalog();
    // The decision may choose an executor, never override the caller/default workload policy.
    const modelRoutes=base.executors.filter(node=>node.eligible).map(node=>{
      const selected=this.ledger.selectExecutionModel(node.id,input.executionModel);
      return {id:digest({nodeId:node.id,...selected.choice}).slice(0,32),description:`${node.id}: ${selected.choice.provider}/${selected.choice.model}${selected.choice.reasoningEffort?" "+selected.choice.reasoningEffort:""} (${selected.executionModel.origin})`,executorId:node.id,provider:selected.choice.provider,model:selected.choice.model,...(selected.choice.reasoningEffort?{reasoningEffort:selected.choice.reasoningEffort}:{}),eligible:true};
    });
    const constraint = input.workspaceId
      ? this.ledger.getWorkspace(input.workspaceId)
      : undefined;
    return {
      ...base,
      stateHash: digest({base:base.stateHash,modelRoutes,policies:base.executors.map(node=>this.ledger.executionModels.view(node.id).policy)}),
      modelRoutes,
      workspaceSelection: "executor" as const,
      ...(input.projectId || input.taskId ? { rankExecutors: true } : {}),
      ...(input.taskId
        ? { tasks: base.tasks.filter((t) => t.id === input.taskId) }
        : {}),
      workspaces: [],
      ...(constraint
        ? {
            executors: base.executors.filter(
              (executor) =>
                executor.id === constraint.nodeId &&
                constraint.state === "ready",
            ),
            modelRoutes: modelRoutes.filter(
              (route) =>
                route.executorId === constraint.nodeId &&
                constraint.state === "ready",
            ),
          }
        : {}),
      ...(input.observationCandidateId
        ? { executors: [], modelRoutes: [], workspaces: [] }
        : {}),
      context: {
        catalog: base.context,
        request: {
          title: input.title,
          description: input.description,
          ...(input.workspaceId
            ? { explicitWorkspaceId: input.workspaceId }
            : {}),
          mode: input.observationCandidateId
            ? "observe-existing-no-dispatch"
            : "request",
        },
      },
    };
  }
  async plan(input: PlanningInput, options: { signal?: AbortSignal } = {}) {
    input = Object.fromEntries(
      Object.entries(input).filter(([, value]) => value !== undefined),
    ) as unknown as PlanningInput;
    const inputDigest = digest(input);
    const existing = this.ledger.getDecision(input.requestId);
    if (existing) {
      if (existing.inputDigest !== inputDigest)
        throw new TaskError("CONFLICT", "Decision request ID reused");
      return this.view(existing);
    }
    if(!input.observationCandidateId)await Promise.all(this.ledger.decisionCatalog().nodes.filter(node=>node.enabled&&node.roles.some(role=>role==="executor"||role==="both")&&this.ledger.executionModels.view(node.nodeId).catalog.state!=="fresh").map(node=>this.ledger.refreshNodeModels(node.nodeId)));
    const snapshot = this.snapshot(input);
    const decisions = this.enabled()
      ? typeof this.decisions === "function"
        ? this.decisions()
        : this.decisions
      : undefined;
    if (!decisions || input.route || input.nodeId) {
      options.signal?.throwIfAborted();
      const assignment = input.route ?? (input.nodeId ? {
        nodeId: input.nodeId,
        ...this.ledger.selectExecutionModel(input.nodeId, input.executionModel).choice,
        requiredCapabilities: [],
      } : undefined);
      const route = assignment && {
        ...assignment,
        ...(input.workspaceId ? { workspaceId: input.workspaceId } : {}),
      };
      if (
        input.route?.workspaceId &&
        input.workspaceId &&
        input.route.workspaceId !== input.workspaceId
      )
        throw new TaskError(
          "FORBIDDEN",
          "Explicit route and Task workspace constraints disagree",
        );
      if (route) this.ledger.validateRoute(route,{admission:true,skipModel:true});
      const proposal: TaskPolicyResult = input.observationCandidateId
        ? {
            kind: "abstain",
            reason: "observation-requires-review",
            protocolReceiptRequired: true,
          }
        : {
            kind: "proposal",
            persistence: input.taskId ? "attach" : "create",
            attachTaskId: input.taskId ?? null,
            executor: route
              ? { id: route.nodeId, description: route.nodeId, eligible: true }
              : null,
            modelRoute: route
              ? {
                  id: digest(route),
                  description: "Explicit execution route",
                  executorId: route.nodeId,
                  provider: route.provider,
                  model: route.model,
                  ...(route.reasoningEffort
                    ? { reasoningEffort: route.reasoningEffort }
                    : {}),
                  eligible: true,
                }
              : null,
            workspace: null,
            reporting: {
              protocolReceiptRequired: true,
              narrative: "none",
              mandatoryReasons: [],
            },
            stateHash: snapshot.stateHash,
            requiresAuthorizationCheck: true,
          };
      const record = this.ledger.recordDecision(`decision:${input.requestId}`, {
        decisionId: input.requestId,
        inputDigest,
        receipt: {
          kind: "deterministic-planning-v1",
          source: "default",
          reason: input.route
            ? "explicit-route"
            : this.enabled()
              ? "service-unavailable"
              : "decision-disabled",
        },
        proposal: proposal as unknown as Json,
        stateHash: snapshot.stateHash,
        validUntil: snapshot.validUntil,
        input: input as unknown as Json,
      }).value;
      return this.view(record);
    }
    const { buildTaskDecisionRequest, consumeTaskDecisionReceipt } =
      await import("./task-policy.js");
    const preset =
      !input.provider && !input.model && !input.reasoningEffort
        ? this.decisionProvider()
        : undefined;
    const route = {
      ...(preset ? { preset } : {}),
      ...(input.provider ? { provider: input.provider } : {}),
      ...(input.model ? { model: input.model } : {}),
      ...(input.reasoningEffort
        ? { reasoningEffort: input.reasoningEffort }
        : {}),
    };
    const request = buildTaskDecisionRequest(
      input.requestId,
      snapshot,
      route,
      this.now(),
    );
    const receipt = await askTaskDecision(decisions, request, options);
    const current = this.snapshot(input);
    const proposal = consumeTaskDecisionReceipt(
      receipt,
      request,
      {
        ...current,
        // Health/slots are advisory ranking evidence. Preserve the submitted
        // descriptions while keeping current catalog identities and eligibility.
        // Admission checks the latest heartbeat and slots after the decision.
        executors: current.executors.map((executor) => ({
          ...executor,
          description:
            snapshot.executors.find((candidate) => candidate.id === executor.id)
              ?.description ?? executor.description,
        })),
      },
      this.now(),
    );
    if (input.taskId && proposal.kind === "proposal") {
      proposal.persistence = "attach";
      proposal.attachTaskId = input.taskId;
    }
    return this.view(
      this.ledger.recordDecision(`decision:${input.requestId}`, {
        decisionId: input.requestId,
        inputDigest,
        receipt: receipt as unknown as Json,
        proposal: proposal as unknown as Json,
        stateHash: snapshot.stateHash,
        validUntil: snapshot.validUntil,
        input: input as unknown as Json,
      }).value,
    );
  }
  private view(record: NonNullable<ReturnType<TaskLedger["getDecision"]>>) {
    const proposal = record.proposal as unknown as TaskPolicyResult;
    return {
      ...record,
      source:
        (record.receipt as { kind?: string }).kind ===
        "deterministic-planning-v1"
          ? "default"
          : "decision",
      routingStatus:
        proposal.kind !== "proposal" || proposal.persistence === "ignore"
          ? "not-requested"
          : proposal.executor && proposal.modelRoute
            ? "ready"
            : "pending-route",
    };
  }
  /** Call only from an authorized task-intent path, never merely on seeing a report. */
  apply(decisionId: string, options: { deferExecution?: boolean } = {}) {
    const existing = this.ledger.commandReceipt(`apply-decision:${decisionId}`);
    if (existing) return existing;
    const record = this.ledger.getDecision(decisionId);
    if (!record) throw new TaskError("NOT_FOUND", "Decision not found");
    const proposal = record.proposal as unknown as TaskDecisionProposal;
    if (proposal.kind !== "proposal")
      throw new TaskError("ABSTAIN", "Decision requires clarification");
    if (proposal.workspace)
      throw new TaskError(
        "WORKSPACE_REPLAN_REQUIRED",
        "Stored scheduler workspace recommendation is no longer executable; replan with a new requestId and let the executor choose its workspace",
      );
    const current = this.snapshot(record.input as unknown as PlanningInput);
    if (
      current.stateHash !== record.stateHash ||
      current.validUntil <= this.now() ||
      record.validUntil <= this.now()
    )
      throw new TaskError("STALE_DECISION", "Catalog changed");
    this.authorize(proposal); // Mandatory deterministic final policy, independent of model confidence.
    const storedInput = record.input as unknown as PlanningInput;
    if (storedInput.observationCandidateId) {
      if (proposal.executor || proposal.modelRoute || proposal.workspace)
        throw new TaskError(
          "OBSERVE_ONLY",
          "Observation cannot select execution",
        );
      return this.ledger.admitObservation(`apply-decision:${decisionId}`, {
        candidateId: storedInput.observationCandidateId,
        action: proposal.persistence,
        ...(proposal.attachTaskId ? { taskId: proposal.attachTaskId } : {}),
      });
    }
    let route: ExecutionRoute | undefined;
    if (proposal.executor && proposal.modelRoute) {
      route = storedInput.route
        ? { ...storedInput.route }
        : {
            nodeId: proposal.executor.id,
            provider: proposal.modelRoute.provider,
            model: proposal.modelRoute.model,
            ...(proposal.modelRoute.reasoningEffort
              ? { reasoningEffort: proposal.modelRoute.reasoningEffort }
              : {}),

            requiredCapabilities: [],
          };
      if (storedInput.workspaceId) route.workspaceId = storedInput.workspaceId;
      const selected=this.ledger.selectExecutionModel(route.nodeId,storedInput.route ?? storedInput.executionModel);
      if(!storedInput.route)route={...route,...selected.choice};
      this.ledger.validateRoute(route,{admission:true,skipModel:true});
    }
    const input = record.input as unknown as PlanningInput;
    return this.ledger.applyDecision(`apply-decision:${decisionId}`, {
      decisionId,
      ...(input.expectedActionVersion
        ? { expectedActionVersion: input.expectedActionVersion }
        : {}),
      ...(options.deferExecution ? { deferExecution: true } : {}),
      currentStateHash: current.stateHash,
      title: input.title,
      description: input.description,
      persistence: proposal.persistence,
      ...(proposal.attachTaskId ? { attachTaskId: proposal.attachTaskId } : {}),
      ...(route ? { route,executionModel:this.ledger.selectExecutionModel(route.nodeId,input.route ?? input.executionModel).executionModel } : {}),
      reporting: proposal.reporting.narrative,
      ...(input.workspaceId || input.route?.workspaceId
        ? { workspaceId: input.workspaceId ?? input.route?.workspaceId }
        : {}),
    });
  }
}

/** The catalog is derived from authoritative records, never supplied by model output. */
export function taskDecisionCatalog(
  ledger: TaskLedger,
  context: Json,
  ttlMs = 30_000,
  now = Date.now(),
): TaskDecisionSnapshot {
  const catalog = ledger.decisionCatalog();
  const host = context as { role?: string; nodeId?: string };
  const health = new Map(ledger.nodeStatuses().map((n) => [n.nodeId, n]));
  const executors = catalog.nodes
    .filter(
      (n) =>
        n.enabled &&
        !(host.role === "planner" && host.nodeId === n.nodeId) &&
        n.roles.some((r) => r === "executor" || r === "both"),
    )
    .map((n) => ({
      id: n.nodeId,
      description: `${n.nodeId}; health: ${health.get(n.nodeId)?.state ?? "unknown"}; available slots: ${health.get(n.nodeId)?.availableSlots ?? "unknown"}; capabilities: ${n.capabilities.join(", ") || "none"}; models: ${n.models.map((model) => `${model.provider}/${model.model}`).join(", ") || "none"}. Prefer suitable online idle executors; a registered offline executor can receive queued work and claim it when online.`,
      eligible: true,
    }));
  const modelRoutes = catalog.nodes.flatMap((n) =>
    n.models.flatMap((model) =>
      [undefined, ...model.reasoningEfforts].map((reasoningEffort) => ({
        id: digest({
          nodeId: n.nodeId,
          ...model,
          reasoningEffort: reasoningEffort ?? null,
        }).slice(0, 32),
        description: `${n.nodeId}: ${model.provider}/${model.model}${reasoningEffort ? " " + reasoningEffort : ""}`,
        executorId: n.nodeId,
        provider: model.provider,
        model: model.model,
        ...(reasoningEffort ? { reasoningEffort } : {}),
        eligible: n.enabled && executors.some((e) => e.id === n.nodeId),
      })),
    ),
  );
  const workspaces = catalog.workspaces
    .filter((w) => w.state === "ready")
    .map((w) => ({
      id: w.workspaceId,
      description: w.label,
      executorId: w.nodeId,
      action: "reuse" as const,
      workspaceRef: w.workspaceId,
      eligible: catalog.nodes.some(
        (n) =>
          n.nodeId === w.nodeId &&
          n.enabled &&
          n.workspaceIds.includes(w.workspaceId),
      ),
    }));
  return {
    stateHash: digest(catalog),
    validUntil: now + ttlMs,
    context,
    tasks: catalog.tasks
      .filter((t) => t.state !== "archived")
      .map((t) => ({ id: t.taskId, description: t.title })),
    executors,
    modelRoutes,
    workspaces,
    mandatoryReportingReasons: [],
  };
}
